"""Состояния анкеты записи на пробное занятие.

Каждое поле класса — один шаг диалога. Пользователь всегда находится
ровно в одном из них, и aiogram по этому состоянию решает, какой
обработчик вызвать. Порядок объявления = порядок прохождения анкеты.
"""

from aiogram.fsm.state import State, StatesGroup


class OrderForm(StatesGroup):
    for_whom = State()  # для кого занятие: ребёнок / взрослый
    name = State()      # имя клиента
    phone = State()     # контактный телефон
    time = State()      # удобное время
    comment = State()   # необязательный комментарий
    confirm = State()   # экран подтверждения заявки
