"""Валидация и нормализация пользовательского ввода.

Здесь НЕТ ни одного упоминания Telegram: на вход — сырая строка,
на выход — либо нормализованное значение, либо ValidationError
с текстом, который можно показать клиенту как есть.

Зачем такое разделение:
  • эти функции тестируются напрямую, без запуска бота (Фаза 8);
  • правила ввода собраны в одном месте, а не размазаны по хендлерам;
  • тот же валидатор переиспользуется, если завтра появится веб-форма.
"""

import re
import unicodedata

import phonenumbers

# ── Ограничения ────────────────────────────────────────────────────
NAME_MIN_LEN = 2
NAME_MAX_LEN = 60
# Минимальная длина непрерывного «слова» из букв. Считаем именно
# отрезок подряд идущих букв, а не сумму по всей строке: иначе
# «А.Б.» проходит как две буквы, хотя именем не является.
NAME_MIN_LETTERS = 2
# Сколько одинаковых букв подряд допустимо. Порог 3, а не 2, —
# иначе сломались бы Алла, Жанна, Филипп, Aaltonen. При этом
# клавиатурный спам «Ааааа» отсекается.
NAME_MAX_REPEAT = 3

# Неалфавитные символы, допустимые в имени:
#   пробел    — составные имена («Анна Мария»)
#   дефис     — «Жан-Клод»
#   апостроф  — «О'Коннор» (два начертания: прямой и типографский)
#   точка     — сокращённая фамилия («Анна П.»)
# Всё остальное (цифры, %, @, эмодзи) в имени человека не встречается.
NAME_EXTRA_CHARS = frozenset(" -'’.")

_NAME_FORMAT_ERROR = (
    "Имя может состоять только из букв, пробела, дефиса, апострофа и точки. "
    "Например: «Анна», «Анна П.» или «Жан-Клод»."
)

_NAME_REPEAT_ERROR = (
    "Не похоже на имя: слишком много одинаковых букв подряд. "
    "Напишите, как к вам обращаться."
)

_NAME_NO_WORD_ERROR = (
    "Не похоже на имя. Напишите его целиком — например, «Анна» или «Анна П.»."
)

TIME_MIN_LEN = 2
TIME_MAX_LEN = 100

COMMENT_MAX_LEN = 500

# Регион по умолчанию для номеров, введённых без кода страны
# («89001234567» → +7…). Переопределяется из конфига школы.
DEFAULT_PHONE_REGION = "RU"


class ValidationError(ValueError):
    """Некорректный ввод.

    Текст исключения показывается КЛИЕНТУ, поэтому формулируем
    по-человечески и всегда подсказываем, как исправить.
    """


# ── Общая очистка ──────────────────────────────────────────────
# Любые пробельные символы (пробел, перенос строки, табуляция,
# юникодные разделители) схлопываем в один обычный пробел.
_SPACES_RE = re.compile(r"\s+")

# Категории Unicode, которые вырезаем целиком:
#   Cc — управляющие символы: ломают логи и разметку;
#   Cf — форматирующие «невидимки»: нулевая ширина, BOM,
#        переопределение направления текста. Ими маскируют спам
#        и подделывают то, как строка выглядит на экране.
# Проверка по категории надёжнее списка кодов: она автоматически
# покрывает символы, добавленные в новых версиях Unicode.
_DROP_CATEGORIES = frozenset({"Cc", "Cf"})


def clean_text(raw: str) -> str:
    """Базовая нормализация любой пользовательской строки."""
    # Сначала пробельные → пробел (иначе перенос строки просто
    # исчезнет, склеив слова), затем выкидываем невидимый мусор.
    text = _SPACES_RE.sub(" ", raw)
    text = "".join(
        ch for ch in text if unicodedata.category(ch) not in _DROP_CATEGORIES
    )

    # NFC — приведение к «составной» форме.
    #
    # Часть клиентов iOS/macOS шлёт «й» и «ё» разложенными: базовая
    # буква «и» + отдельный знак краткости. У этого знака категория Mn,
    # он не проходит isalpha() и не входит в белый список символов —
    # и honest-имя «Андрей» получало отказ. NFC склеивает пару в один
    # символ «й», после чего она проходит как обычная буква.
    #
    # Делаем ПОСЛЕ выреза невидимок: если между буквой и знаком был
    # вставлен zero-width символ, после его удаления они становятся
    # соседними и NFC отрабатывает правильно.
    text = unicodedata.normalize("NFC", text)

    return text.strip()


def _count_letters(text: str) -> int:
    """Сколько в строке именно букв (не цифр, не эмодзи, не знаков)."""
    return sum(1 for ch in text if ch.isalpha())


def _longest_letter_run(text: str) -> int:
    """Длина самого длинного непрерывного отрезка букв.

    Именно «слово», а не сумма букв по строке: в «А.Б.» букв две,
    но настоящего слова нет — это не имя.
    """
    longest = current = 0
    for ch in text:
        if ch.isalpha():
            current += 1
            longest = max(longest, current)
        else:
            current = 0
    return longest


def _has_long_repeat(text: str) -> bool:
    """Есть ли NAME_MAX_REPEAT+ одинаковых букв подряд («Ааааа»).

    Сравниваем регистронезависимо, иначе «ААА» проскочит. casefold()
    применяем к одиночным символам уже после NFC — так безопасно.
    """
    run = 1
    for prev, cur in zip(text, text[1:]):
        if prev.isalpha() and prev.casefold() == cur.casefold():
            run += 1
            if run >= NAME_MAX_REPEAT:
                return True
        else:
            run = 1
    return False


def _is_name_char(ch: str) -> bool:
    """Допустим ли символ в имени человека.

    isalpha() покрывает любой алфавит — кириллицу, латиницу, армянский,
    грузинский. Никаких списков «разрешённых языков»: клиент может
    оказаться кем угодно, а вот «%» в имени не бывает ни у кого.
    """
    return ch.isalpha() or ch in NAME_EXTRA_CHARS


# ── Имя ────────────────────────────────────────────────────────────
def validate_name(raw: str) -> str:
    """Проверяет имя клиента и возвращает нормализованное значение."""
    name = clean_text(raw)

    if not name:
        raise ValidationError("Имя не может быть пустым. Напишите, как к вам обращаться.")

    if len(name) < NAME_MIN_LEN:
        raise ValidationError(
            f"Имя слишком короткое (нужно минимум {NAME_MIN_LEN} символа). "
            "Напишите, как к вам обращаться."
        )

    if len(name) > NAME_MAX_LEN:
        raise ValidationError(
            f"Имя слишком длинное (максимум {NAME_MAX_LEN} символов). "
            "Напишите, пожалуйста, короче."
        )

    # ── Проверка формата ──
    # Белый список символов. Именно он отсекает «g%G%», «Анна2» и эмодзи:
    # подсчёта букв здесь недостаточно — в «g%G%» их формально две.
    if any(not _is_name_char(ch) for ch in name):
        raise ValidationError(_NAME_FORMAT_ERROR)

    # Имя начинается с буквы: «.Анна», «-Анна» — мусор.
    if not name[0].isalpha():
        raise ValidationError(_NAME_FORMAT_ERROR)

    # Заканчивается буквой или точкой (сокращённая фамилия).
    # Отсекает «Анна-», «Анна '».
    if not (name[-1].isalpha() or name[-1] == "."):
        raise ValidationError(_NAME_FORMAT_ERROR)

    # Два неалфавитных символа подряд: «Ан..», «Жан--Клод», «А . Б».
    # Исключение — пара «точка + пробел»: она встречается в легитимном
    # «И. Иванов», который раньше отсекался наравне с мусором.
    if any(
        not name[i].isalpha()
        and not name[i + 1].isalpha()
        and not (name[i] == "." and name[i + 1] == " ")
        for i in range(len(name) - 1)
    ):
        raise ValidationError(_NAME_FORMAT_ERROR)

    # Нужно хотя бы одно настоящее слово. Считаем непрерывный отрезок
    # букв, а не сумму по строке: иначе «А.Б.» и «А-Б» проходят, набрав
    # две буквы по разным «словам».
    #
    # Осознанный размен: имя из одних инициалов «И.И.» теперь отклоняется.
    # Для музыкальной школы это экзотика, а мусора такой формат пропускает
    # много. «Анна П.» и «А. Иванов» работают — в них есть слово.
    if _longest_letter_run(name) < NAME_MIN_LETTERS:
        raise ValidationError(_NAME_NO_WORD_ERROR)

    # Клавиатурный спам «Ааааа»: формат верный, но именем не является.
    if _has_long_repeat(name):
        raise ValidationError(_NAME_REPEAT_ERROR)

    return name


# ── Телефон ────────────────────────────────────────────────────────
def validate_phone(raw: str, region: str = DEFAULT_PHONE_REGION) -> str:
    """Проверяет телефон и возвращает его в формате E.164 (+79001234567).

    E.164 — международный стандарт записи номера. Храним именно его:
    номер, введённый как «8 (900) 123-45-67» и как «+7 900 1234567»,
    превращается в одну и ту же строку. Иначе в таблице у владельца
    будет каша из форматов, а один клиент — как три разных.
    """
    text = clean_text(raw)

    if not text:
        raise ValidationError("Номер не может быть пустым.")

    try:
        # parse понимает скобки, дефисы и пробелы. region нужен для
        # номеров без «+»: по нему библиотека достраивает код страны.
        number = phonenumbers.parse(text, region)
    except phonenumbers.NumberParseException:
        raise ValidationError(
            "Не удалось распознать номер. "
            "Напишите его в формате +7 900 123-45-67 "
            "или нажмите кнопку «Поделиться контактом»."
        ) from None

    # is_valid_number — строгая проверка по правилам страны
    # (существует ли такой код оператора, верна ли длина).
    if not phonenumbers.is_valid_number(number):
        raise ValidationError(
            "Такого номера не существует. Проверьте, пожалуйста, и напишите ещё раз — "
            "например: +7 900 123-45-67."
        )

    return phonenumbers.format_number(number, phonenumbers.PhoneNumberFormat.E164)


def format_phone_display(e164: str) -> str:
    """Красивый вид номера для показа: +7 900 123-45-67.

    Хранить удобно E.164, а показывать человеку — с разделителями.
    """
    try:
        number = phonenumbers.parse(e164, None)
        return phonenumbers.format_number(
            number, phonenumbers.PhoneNumberFormat.INTERNATIONAL
        )
    except phonenumbers.NumberParseException:
        # На всякий случай: показать как есть лучше, чем упасть.
        return e164


# ── Удобное время ──────────────────────────────────────────────────
def validate_time(raw: str) -> str:
    """Проверяет пожелание по времени (пока свободный текст).

    В будущем этот шаг заменится выбором конкретного слота —
    тогда поменяется только эта функция и клавиатура шага.
    """
    text = clean_text(raw)

    if not text:
        raise ValidationError(
            "Напишите, когда вам удобно — например, «будни после 18:00»."
        )

    if len(text) < TIME_MIN_LEN:
        raise ValidationError(
            "Слишком коротко. Напишите подробнее — например, «суббота утром»."
        )

    if len(text) > TIME_MAX_LEN:
        raise ValidationError(
            f"Слишком длинно (максимум {TIME_MAX_LEN} символов). "
            "Напишите короче — например, «будни после 18:00»."
        )

    # Должно быть хоть что-то осмысленное: буква или цифра.
    if not any(ch.isalnum() for ch in text):
        raise ValidationError(
            "Не удалось понять время. Напишите словами или цифрами — "
            "например, «пн-пт после 19:00»."
        )

    return text


# ── Комментарий (необязательный) ───────────────────────────────────
def validate_comment(raw: str) -> str:
    """Проверяет комментарий. Пустой комментарий допустим."""
    text = clean_text(raw)

    if len(text) > COMMENT_MAX_LEN:
        raise ValidationError(
            f"Комментарий слишком длинный (максимум {COMMENT_MAX_LEN} символов). "
            "Напишите, пожалуйста, короче."
        )

    return text
