"""Форматирование дат и времени для показа человеку.

Русские названия заданы таблицами, а не через strftime("%B"):
формат даты зависит от локали ОС, и на сервере с английской локалью
клиент увидел бы «9 August, Sat». Таблица делает вывод одинаковым
где угодно.

Функции чистые — тестируются без бота.
"""

from datetime import date, time

# Родительный падеж: «9 августа», а не «9 август».
MONTHS_GENITIVE = (
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)

# Порядок совпадает с date.weekday(): 0 — понедельник.
WEEKDAYS_SHORT = ("пн", "вт", "ср", "чт", "пт", "сб", "вс")
WEEKDAYS_FULL = (
    "понедельник", "вторник", "среда", "четверг",
    "пятница", "суббота", "воскресенье",
)

MONTHS_SHORT = (
    "янв", "фев", "мар", "апр", "мая", "июн",
    "июл", "авг", "сен", "окт", "ноя", "дек",
)


def format_day_button(day: date) -> str:
    """Короткая подпись для кнопки: «9 авг, сб».

    Кнопок в ряду две, поэтому подпись должна быть компактной,
    но день недели нужен — по нему люди и выбирают.
    """
    return f"{day.day} {MONTHS_SHORT[day.month - 1]}, {WEEKDAYS_SHORT[day.weekday()]}"


def format_day_full(day: date) -> str:
    """Развёрнутая дата для заголовка: «9 августа, суббота»."""
    return (
        f"{day.day} {MONTHS_GENITIVE[day.month - 1]}, "
        f"{WEEKDAYS_FULL[day.weekday()]}"
    )


def format_slot(day: date, slot: time) -> str:
    """Итоговая запись времени для заявки: «9 августа (сб), 18:00».

    Именно эта строка уезжает владельцу в уведомление и в таблицу,
    поэтому она должна читаться без пояснений.
    """
    return (
        f"{day.day} {MONTHS_GENITIVE[day.month - 1]} "
        f"({WEEKDAYS_SHORT[day.weekday()]}), {slot:%H:%M}"
    )


# ── Кодирование времени для callback_data ──────────────────────────
# Внутри callback_data поля разделяются двоеточием, поэтому значение
# «18:00» сломало бы разбор строки обратно. Кодируем как «1800».


def time_to_hm(slot: time) -> str:
    """time(18, 0) → «1800»."""
    return f"{slot.hour:02d}{slot.minute:02d}"


def hm_to_time(value: str) -> time | None:
    """«1800» → time(18, 0). None, если строка испорчена.

    Данные приходят из callback_data, то есть снаружи, — доверять им
    нельзя. Возвращаем None вместо исключения, чтобы вызывающий код
    мог показать понятное сообщение.
    """
    if len(value) != 4 or not value.isdigit():
        return None
    try:
        return time(int(value[:2]), int(value[2:]))
    except ValueError:
        return None
